from pathlib import Path
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parents[1]; html=root/'SkyMusicStudio_独立版.html'
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--autoplay-policy=no-user-gesture-required'])
 page=b.new_page(viewport={'width':1366,'height':768},accept_downloads=True)
 err=[];page.on('pageerror',lambda x:err.append(str(x)))
 page.set_content(html.read_text(encoding="utf-8"),timeout=60000);page.wait_for_timeout(800)
 print('boot',page.locator('.song-card').count(),page.locator('#libraryCount').inner_text(),err)
 page.screenshot(path=str(root/'tests/home_1366.png'))
 page.locator('#newProjectHome').click();page.wait_for_timeout(350)
 print('new',page.locator('#songTitle').inner_text(),page.locator('.beat').count(),page.locator('#studioDrawer').is_visible(),err)
 page.screenshot(path=str(root/'tests/new_project.png'))
 page.locator('#closeDrawer').click()
 page.locator('#backLibrary').click()
 print('library',page.locator('#libraryCount').inner_text(),err)
 page.locator('.card-play').filter(has_text='▶').first.click();page.wait_for_timeout(450)
 print('player',page.locator('#songTitle').inner_text(),page.locator('#noteCountHeader').inner_text(), 'keys', page.locator('.key-tile').count(), 'cells', page.locator('.beat').count(),err)
 page.screenshot(path=str(root/'tests/player_1366.png'))
 page.locator('#editWorkstation').click();page.wait_for_timeout(100)
 print('drawer',page.locator('#studioDrawer').is_visible(),page.locator('#eventInfo').inner_text(),err)
 page.locator('#eventDuration').fill('305');page.locator('#applyEvent').click()
 print('edit duration',page.evaluate('window.__SKY_V03_TEST__.state.project.score.events[0].durationMs'))
 page.locator('#undoEdit').click();print('undo',page.evaluate('window.__SKY_V03_TEST__.state.project.score.events[0].durationMs'))
 page.locator('#redoEdit').click();print('redo',page.evaluate('window.__SKY_V03_TEST__.state.project.score.events[0].durationMs'))
 page.locator('[data-panel="scene"]').click();page.locator('[data-theme-choice="cinema"]').click()
 print('scene',page.evaluate('window.__SKY_V03_TEST__.state.project.theme'), 'class', page.locator('#playerView').get_attribute('class'))
 page.screenshot(path=str(root/'tests/scene_cinema.png'))
 page.locator('[data-panel="project"]').click();page.locator('#projectTitle').fill('冬夜钢琴测试');page.locator('#saveProjectInfo').click()
 print('rename',page.locator('#songTitle').inner_text())
 page.locator('[data-panel="score"]').click()
 for btn,name in [('#exportMidi','test.mid'),('#exportCsv','test.csv'),('#exportJson','test.json'),('#exportSkymusic','test.skymusic')]:
  with page.expect_download(timeout=15000) as d:page.locator(btn).click()
  f=d.value;f.save_as(str(root/'tests'/name));print('download',f.suggested_filename,(root/'tests'/name).stat().st_size)
 page.locator('#closeDrawer').click();page.locator('#backLibrary').click()
 page.locator('#songSearch').fill('冬夜');print('search cards',page.locator('.song-card').count())
 page.locator('#songSearch').fill('')
 page.locator('[data-import]').first.click(); print('import open',page.locator('#importDialog').is_visible())
 page.locator('#fileInput').set_input_files(str(root/'tests/test.skymusic'));page.wait_for_timeout(450)
 print('roundtrip',page.locator('#songTitle').inner_text(),page.evaluate('window.__SKY_V03_TEST__.state.project.theme.id'))
 print('Errors:',err)
 b.close()
